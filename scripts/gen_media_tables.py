#!/usr/bin/env python3
"""Regenerate src/media/h264_tables.h and src/media/aac_tables.h from FFmpeg's libavcodec sources.

The tables are numeric data of the H.264 and MPEG-4 AAC standards (CABAC context initialisation, the arithmetic
coder's range table, the deblocking thresholds, the AAC Huffman codebooks and scalefactor band offsets). FFmpeg
(LGPL-2.1-or-later) is only the convenient machine-readable copy; nothing else is taken from it.

    scripts/gen_media_tables.py <dir with FFmpeg's libavcodec/*.c>

Needs: h264_cabac.c cabac.c h264_loopfilter.c aactab.c. The output is committed; this runs only to refresh it.
"""
from __future__ import annotations

import logging
import re
import sys
from pathlib import Path

NUM = re.compile(r"-?0x[0-9a-fA-F]+|-?\d+")


LOG = logging.getLogger("gen_media_tables")


def body(text: str, name: str) -> str:
    """The text between the braces of `name[...] = { ... }`, nested braces included."""
    m = re.search(r"\b" + re.escape(name) + r"\b[^=;{]*=\s*\{", text)
    if not m:
        raise SystemExit(f"array {name} not found")
    i = m.end() - 1
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    raise SystemExit(f"array {name} is not closed")


def nums(s: str) -> list[int]:
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    s = re.sub(r"//[^\n]*", "", s)
    return [int(x, 0) for x in NUM.findall(s)]


def fmt(vals: list, per_line: int = 16, width: int = 0, indent: str = "    ") -> str:
    out = []
    for i in range(0, len(vals), per_line):
        out.append(indent + ",".join(f"{v:{width}d}" for v in vals[i:i + per_line]) + ",")
    return "\n".join(out)


def c_array(ctype: str, name: str, dims: str, vals: list, per_line: int = 16, width: int = 0, static: bool = True) -> str:
    return (f"{'static ' if static else ''}const {ctype} {name}{dims} = {{\n{fmt(vals, per_line, width)}\n}};\n")


def h264(src: Path) -> str:
    cabac = (src / "h264_cabac.c").read_text()
    lf = (src / "h264_loopfilter.c").read_text()
    out = ["/* Generated by scripts/gen_media_tables.py from the H.264 standard's tables (via FFmpeg's copy). Do not edit. */\n"]

    # CABAC context initialisation (m, n) pairs: contexts 0..459 cover everything 4:2:0 frame-coded video uses.
    n_ctx = 460
    init_i = nums(body(cabac, "cabac_context_init_I"))
    init_pb = nums(body(cabac, "cabac_context_init_PB"))
    assert len(init_i) == 1024 * 2 and len(init_pb) == 3 * 1024 * 2
    vals = init_i[:n_ctx * 2]
    for idc in range(3):
        vals += init_pb[idc * 2048:idc * 2048 + n_ctx * 2]
    out.append(f"#define H264_CABAC_CTX {n_ctx}\n")
    out.append("/* [0] = I and SI slices, [1 + cabac_init_idc] = P, SP and B slices; {m, n} */\n")
    rows = []
    for tbl in range(4):
        pairs = [f"{{{vals[(tbl * n_ctx + i) * 2]:4d},{vals[(tbl * n_ctx + i) * 2 + 1]:4d}}}" for i in range(n_ctx)]
        rows.append("  {\n" + "\n".join("    " + ",".join(pairs[k:k + 8]) + "," for k in range(0, n_ctx, 8)) + "\n  },")
    out.append("static const int8_t h264_cabac_init[4][H264_CABAC_CTX][2] = {\n" + "\n".join(rows) + "\n};\n")

    # rangeTabLPS[pStateIdx][qCodIRangeIdx], read back from FFmpeg's packed layout.
    tab = nums(body((src / "cabac.c").read_text(), "ff_h264_cabac_tables"))
    lps = [tab[512 + q * 128 + s * 2] & 0xFF for s in range(64) for q in range(4)]
    out.append("/* rangeTabLPS[pStateIdx * 4 + qCodIRangeIdx] */\nstatic const uint8_t h264_range_lps[64 * 4] = {\n" + fmt(lps, 8, 3) + "\n};\n")

    # Deblocking: alpha'(indexA), beta'(indexB), tC0'[indexA * 3 + bS - 1]; FFmpeg's tables are padded by 52 on each side.
    alpha = nums(body(lf, "alpha_table"))[52:104]
    beta = nums(body(lf, "beta_table"))[52:104]
    tc0 = nums(body(lf, "tc0_table"))
    tc0 = [tc0[4 * (52 + i) + b] for i in range(52) for b in (1, 2, 3)]
    out.append(c_array("uint8_t", "h264_alpha", "[52]", alpha, 13, 3))
    out.append(c_array("uint8_t", "h264_beta", "[52]", beta, 13, 2))
    out.append(c_array("uint8_t", "h264_tc0", "[52 * 3]", tc0, 15, 2))

    # Residual block significance maps of 8x8 blocks, frame coded: ctxIdxInc of significant_coeff_flag and
    # last_significant_coeff_flag by position in the scan.
    sig = nums(re.search(r"significant_coeff_flag_offset_8x8\[2\]\[63\] = \{(.*?)\n    \};", cabac, re.S).group(1))
    assert len(sig) == 126
    last8 = tab[len(tab) - 63:]    # the tail of FFmpeg's packed table
    assert last8[:3] == [0, 1, 1] and last8[-1] == 8
    out.append(c_array("uint8_t", "h264_sig8x8", "[63]", sig[:63], 16, 2))
    out.append(c_array("uint8_t", "h264_last8x8", "[63]", last8, 16, 1))
    return "\n".join(out)


def aac(src: Path) -> str:
    t = (src / "aactab.c").read_text()
    out = ["/* Generated by scripts/gen_media_tables.py from the MPEG-4 AAC standard's tables (via FFmpeg's copy). Do not edit. */\n"]

    sf_code = nums(body(t, "ff_aac_scalefactor_code"))
    sf_bits = nums(body(t, "ff_aac_scalefactor_bits"))
    assert len(sf_code) == len(sf_bits) == 121
    out.append(c_array("uint32_t", "aac_sf_codes", "[121]", sf_code, 8, 0))
    out.append(c_array("uint8_t", "aac_sf_bits", "[121]", sf_bits, 16, 2))

    sizes = [81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289]
    for n in range(1, 12):
        codes = nums(body(t, f"codes{n}"))
        bits = nums(body(t, f"bits{n}"))
        assert len(codes) == len(bits) == sizes[n - 1], (n, len(codes), len(bits))
        out.append(c_array("uint16_t", f"aac_cb{n}_codes", f"[{len(codes)}]", codes, 12, 0))
        out.append(c_array("uint8_t", f"aac_cb{n}_bits", f"[{len(bits)}]", bits, 24, 2))

    # Scalefactor band offsets by sampling_frequency_index 0..12 (96000 ... 7350 Hz).
    def pick(table: str) -> list[str]:
        m = re.search(r"\b" + table + r"\[\]\s*=\s*\{(.*?)\};", t, re.S)
        return re.findall(r"swb_offset_\w+", re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S))

    for kind, n_swb in (("1024", "ff_aac_num_swb_1024"), ("128", "ff_aac_num_swb_128")):
        names = pick("ff_swb_offset_" + kind)
        counts = nums(body(t, n_swb))
        uniq = []
        for nm in names:
            if nm not in uniq:
                uniq.append(nm)
        for nm in uniq:
            vals = nums(body(t, nm))
            out.append(c_array("uint16_t", "aac_" + nm, f"[{len(vals)}]", vals, 14, 4))
        idx = ", ".join(f"aac_{nm}" for nm in names)
        out.append(f"static const uint16_t *const aac_swb_{kind}[13] = {{ {idx} }};\n")
        out.append(f"static const uint8_t aac_num_swb_{kind}[13] = {{ {', '.join(map(str, counts))} }};\n")
    def fnums(name: str) -> list[float]:
        body_ = re.search(r"\b" + name + r"\[\d*\]\s*=\s*\{(.*?)\};", t, re.S).group(1)
        return [float(x) for x in re.findall(r"-?\d+\.\d+", body_)]

    # TNS coefficient dequantisation: [coef_compress][coef_res] -> parcor values indexed by the coded value
    for compress in (0, 1):
        for res in (0, 1):
            vals = fnums(f"tns_tmp2_map_{compress}_{res + 3}")
            out.append(f"static const float aac_tns_map_{compress}_{res + 3}[{len(vals)}] = {{ "
                       + ", ".join(f"{v:.8f}f" for v in vals) + " };\n")
    out.append("static const uint8_t aac_tns_max_bands_1024[13] = { "
               + ", ".join(map(str, nums(body(t, "ff_tns_max_bands_1024")))) + " };\n")
    out.append("static const uint8_t aac_tns_max_bands_128[13] = { "
               + ", ".join(map(str, nums(body(t, "ff_tns_max_bands_128")))) + " };\n")
    return "\n".join(out)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1])
    dst = Path(__file__).resolve().parent.parent / "src" / "media"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "h264_tables.h").write_text(h264(src))
    (dst / "aac_tables.h").write_text(aac(src))
    LOG.info("wrote %s and %s", dst / "h264_tables.h", dst / "aac_tables.h")


if __name__ == "__main__":
    main()
