#!/usr/bin/env python3
"""Writes the game-independent ppu_recomp.h that the host binary is built against.

usage: make_host_header.py <toolkit dir> <out header>

The host is built before any game is lifted, so it cannot include the per-game header the lifter writes. That header is
the lifter's own HEADER_PREAMBLE (context layout, memory helpers, fence macro, func_entry) followed by one prototype per
lifted function. The host takes the preamble verbatim, so the two cannot drift apart, and replaces the one thing that is
per game, the function table: the host does not link it, it finds `function_table` in the game module at load time and
keeps it in g_game_function_table.
"""
import importlib.util
import sys
from pathlib import Path

TABLE_DECL = "extern const func_entry function_table[];"
COUNT_DECL = "extern const uint64_t  function_table_count;  /* entries, excluding sentinel */"


def host_header(toolkit: Path) -> str:
    spec = importlib.util.spec_from_file_location("ppu_lifter", toolkit / "tools" / "ppu_lifter.py")
    lifter = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(lifter)
    text = lifter.HEADER_PREAMBLE
    for decl in (TABLE_DECL, COUNT_DECL):
        if text.count(decl) != 1:
            sys.exit(f"make_host_header: lifter preamble no longer contains {decl!r}; update this script")
    text = text.replace(TABLE_DECL, "extern const func_entry *g_game_function_table;   /* set from the game module */")
    text = text.replace(COUNT_DECL, "extern uint64_t g_game_function_table_count;      /* entries, excluding sentinel */")
    return (
        "/* Generated by scripts/make_host_header.py from the lifter's header preamble. Host build only. */\n"
        + text
        + "\n/* The runtime spells the table the way a monolithic build links it. */\n"
        "#define function_table       g_game_function_table\n"
        "#define function_table_count g_game_function_table_count\n"
    )


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(host_header(Path(sys.argv[1])))
